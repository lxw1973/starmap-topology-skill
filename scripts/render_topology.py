#!/usr/bin/env python3
"""把拓扑数据渲染成一张 SVG/PNG 拓扑图。

输入 JSON 结构:
{
  "network": "192.168.1.0/24",
  "gateway": {"ip": "192.168.1.1", "role": "路由器/网关", "ports": ["53/dns","80/http","443/https"],
               "mac": "e8:d7:65:c9:41:4e"},
  "hosts": [{"ip": "192.168.1.21", "role": "接入设备", "ports": ["80/http"]}, ...]
}
用法: python3 render_topology.py topology.json out.html
"""
import json, sys, html

def esc(s): return html.escape(str(s))

def node(x, y, w, h, title, sub, ports, color="#38bdf8", accent="#0ea5e9"):
    lines = "".join(
        f'<text x="{x+w/2}" y="{y+h-16-len(ports)*1}" font-size="11" fill="#94a3b8" text-anchor="middle">{esc(p)}</text>'
        for p in [])
    port_lines = ""
    for i, p in enumerate(ports):
        port_lines += f'<text x="{x+w-12}" y="{y+26+i*15}" font-size="11" fill="#7dd3fc" text-anchor="end">{esc(p)}</text>'
    return f'''<g>
  <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="12" fill="#0f172a" stroke="{accent}" stroke-width="1.5"/>
  <rect x="{x}" y="{y}" width="6" height="{h}" rx="3" fill="{accent}"/>
  <text x="{x+18}" y="{y+24}" font-size="15" font-weight="600" fill="#e2e8f0">{esc(title)}</text>
  <text x="{x+18}" y="{y+44}" font-size="12" fill="#94a3b8">{esc(sub)}</text>
  {port_lines}
</g>'''

def main():
    data = json.load(open(sys.argv[1], encoding="utf-8"))
    out = sys.argv[2]
    W, H = 1400, 860
    gw = data["gateway"]; hosts = data.get("hosts", [])
    # 布局：接入点 -> 网关 -> 终端
    net_x, net_y, net_w, net_h = 60, 330, 250, 120
    gw_x, gw_y, gw_w, gw_h = 430, 320, 300, 150
    hx0, hy0, hw, hh, gap = 880, 150, 380, 130, 90
    parts = []
    parts.append(f'<rect width="{W}" height="{H}" fill="#020617"/>')
    parts.append(f'<text x="60" y="70" font-size="26" font-weight="700" fill="#e2e8f0">家庭网络拓扑</text>')
    parts.append(f'<text x="60" y="100" font-size="14" fill="#64748b">{esc(data.get("network",""))} · StarMap 资产星图数据 · nmap 实测端口</text>')
    # 云/互联网
    parts.append(node(net_x, net_y, net_w, net_h, "互联网 / ISP", "WAN 侧", [], "#64748b", "#475569"))
    # 网关
    ports = gw.get("ports", [])
    parts.append(node(gw_x, gw_y, gw_w, gw_h, gw["ip"], gw.get("role","网关"), ports, "#f59e0b", "#f59e0b"))
    if gw.get("mac"):
        parts.append(f'<text x="{gw_x+18}" y="{gw_y+gw_h-14}" font-size="11" fill="#8a6d3b">{esc(gw["mac"])}</text>')
    # 主机
    total_h = len(hosts)*hh + max(0, len(hosts)-1)*gap
    start_y = (H - total_h)//2 + 20
    for i, h in enumerate(hosts):
        y = start_y + i*(hh+gap)
        parts.append(node(hx0, y, hw, hh, h["ip"], h.get("role","终端"), h.get("ports", []), "#38bdf8", "#0ea5e9"))
        # 连线到网关
        x1, y1 = gw_x+gw_w, gw_y+gw_h/2
        x2, y2 = hx0, y+hh/2
        mx = (x1+x2)/2
        parts.append(f'<path d="M {x1} {y1} C {mx} {y1}, {mx} {y2}, {x2} {y2}" fill="none" stroke="#1e40af" stroke-width="1.5" stroke-dasharray="5 4"/>')
    # 网关到互联网
    parts.append(f'<path d="M {net_x+net_w} {net_y+net_h/2} C 370 {net_y+net_h/2}, 360 {gw_y+gw_h/2}, {gw_x} {gw_y+gw_h/2}" fill="none" stroke="#334155" stroke-width="1.5"/>')
    parts.append(f'<text x="{W-60}" y="{H-30}" font-size="11" fill="#334155" text-anchor="end">generated by starmap-topology skill</text>')
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" font-family="PingFang SC, Hiragino Sans GB, Microsoft YaHei, sans-serif">' + "".join(parts) + '</svg>'
    open(out, "w", encoding="utf-8").write(f'<!doctype html><html><body style="margin:0;background:#020617">{svg}</body></html>')
    print("wrote", out)

if __name__ == "__main__":
    main()
